export type TeaType =
    | "green"
    | "black"
    | "oolong"
    | "pu-erh"
    | "white"
    | "yellow";

/**
 * Категория по стандартам: ISO 20715:2023 и GB/T, шесть значений.
 *
 * Это **метаданные, а не маршрутизация.** `TeaType` задаёт URL
 * (`teaTypePath`), подпись (`TEA_TYPE_LABELS`) и фильтр; `standardCategory`
 * не задаёт ничего из этого и никогда не должна появиться в пути, в слаге или
 * в ключе фильтра. Решение пользователя 06.11.2026: пуэр по стандарту —
 * тёмный чай, но URL остаётся `/tea/pu-erh`, потому что «пуэр» в ядре
 * запросов многократно частотнее «хэй ча» (171 против 11+7+12).
 *
 * Поле заполняют только там, где оно расходится с ожидаемым для типа:
 * `pu-erh` → `dark`, остальные пять типов → одноимённое значение. Расхождение
 * бывает и в другую сторону: Аньцзи байча по названию «белый чай», а по
 * стандарту зелёный. Согласовано с justea-sources 07.11.2026.
 */
export type StandardTeaCategory =
    | "green"
    | "black"
    | "oolong"
    | "white"
    | "yellow"
    | "dark";

/**
 * Подтип пуэра: шу (постферментированный «влажным скирдованием») и шэн
 * (прессованный, ферментируется выдержкой).
 *
 * Отдельных страниц типа шу и шэн не требуют: их спрос сортового уровня
 * (`shu-pu-erh` 82 + 131, `sheng-pu-erh` 17 + 26), то есть это обычные
 * страницы сортов `/shu-pu-erh` и `/sheng-pu-erh`. Подтип — атрибут данных,
 * не маршрут.
 *
 * Имя поля привязано к пуэру сознательно. Любао, фу чжуань и хунаньские хэй
 * ча — тоже тёмные постферментированные, но «шу/шэн» к ним неприменимы;
 * когда они появятся, justea-sources предлагает нормативное
 * `postFermentation: "none" | "piled" | "aged"` (ISO 20715 п. 3.11,
 * GB/T 22111 п. 4.3). Пока тёмных чаёв кроме пуэра нет, и `puerhKind` ничего
 * не ломает.
 */
export type PuerhKind = "shu" | "sheng";

/**
 * Форма прессовки. Значения — ровно те четыре, что названы в
 * GB/T 22111-2008 п. 5.2.2: блин (圆饼形), точа (碗臼形), кирпич (方形),
 * колонна (柱形).
 *
 * Отсутствие поля означает рассыпной чай. Внимание: **по GB/T 22111 п. 5.1 и
 * 6.5.2 рассыпного шэна не существует** — рассыпным бывает только шу, шэн
 * становится пуэром лишь после прессования. Поэтому запись с
 * `puerhKind: "sheng"` обязана иметь `pressedForm`, иначе она противоречит
 * стандарту, на который мы же ссылаемся. Проверяется в
 * `scripts/check-tea-data.mjs`.
 */
export type PressedForm = "cake" | "tuo" | "brick" | "column";

/**
 * Короткая статичная сноска-предосторожность.
 *
 * Решение пользователя 06.11.2026: о пользе и вреде чая не пишем вовсе
 * (раздел `/health` снят целиком), вместо этого — одна фраза у тех чаёв, где
 * она обоснована источником уровня A или B. Пусто там, где обоснования нет;
 * выдумывать повод нельзя, поэтому из восьми чаёв каталога сноска обоснована
 * у двух.
 *
 * Поле принадлежит чаю, а не способу заваривания: предосторожность относится
 * к листу, а не к тому, как его залили.
 *
 * **В структурированные данные не выводится, и это решение, а не
 * недоработка** (принято 07.11.2026). У `Product` и `HowTo` нет поля со
 * значением «предосторожность», а натягивать её на `additionalProperty` — то
 * же искажение типов, из-за которого `meta.origin` не идёт в
 * `countryOfOrigin`. Главное же: JSON-LD усиливает то, что в него попадает, и
 * вынести сноску в разметку значило бы просить поисковик показать её в
 * сниппете — прямо против решения «о здоровье не пишем». Правило соответствия
 * работает в одну сторону: разметка не должна заявлять больше, чем видно;
 * видимый контент без разметки — нормально.
 */
export interface TeaCaution {
    /** Одно предложение. Без медицинских утверждений и без дозировок. */
    text: string;
    /**
     * Идентификаторы источников из `docs/sources/catalog.json` (ключи объекта
     * `sources`). Сноска о здоровье без прослеживаемого источника — ровно то,
     * что в проекте убирается, поэтому поле обязательное и непустое.
     * На странице не отображается: читателю нужен текст, а не ключ `efsa-…`.
     */
    sources: string[];
    /** Уровень обоснованности источника по шкале justea-sources. */
    level?: "A" | "B";
    /** Чем именно обосновано — для ревью, не для показа. */
    basis?: string;
}

export type BrewMethodType =
    | "gongfu"
    | "western"
    | "grandpa"
    | "cold-brew"
    | "iced";

export interface BrewMethod {
    id: string;
    name: string;
    type: BrewMethodType;
    description: string;
    /** Гр чая на 100 мл воды */
    ratio: number;
    temperature: {
        from: number;
        to: number;
    };
    /** Время проливов в секундах */
    infusions: {
        number: number;
        time: number;
        notes?: string;
    }[];
    /** Особые заметки по приготовлению */
    notes?: string[];
}

export interface Tea {
    id: string;
    slug: string;
    name: string;
    photo?: string;
    description?: string;
    type: TeaType;

    /**
     * Категория по стандарту, если она расходится с ожидаемой для `type`.
     * Не влияет на URL и фильтры — см. `StandardTeaCategory`.
     */
    standardCategory?: StandardTeaCategory;

    /** Подтип пуэра. Осмысленно только при `type: "pu-erh"`. */
    puerhKind?: PuerhKind;

    /**
     * Форма прессовки; отсутствие поля означает рассыпной чай.
     * При `puerhKind: "sheng"` обязательна — см. `PressedForm`.
     */
    pressedForm?: PressedForm;

    /**
     * Народные и ошибочные написания названия: «шен пуэр» при основном «шэн
     * пуэр», «гекуро» при «гёкуро», «оолонг» при «улун».
     *
     * Нужны потому, что частотнее часто именно неверное написание: «шен
     * пуэр» — 10 882 показа в месяц против 1 621 у «шэн пуэра», то есть в
     * 6,7 раза. Поиск по сайту ищет и по ним (`lib/search.ts`), чтобы человек
     * находил чай так, как он его называет. В тексты и заголовки синонимы не
     * подставляются: подмешивать варианты написания в видимый текст ради
     * поиска — это переоптимизация, за которую страницы и понижают.
     */
    synonyms?: string[];

    /** Основной способ приготовления (для отображения в списке) */
    primaryBrewMethod: BrewMethodType;

    /** Все доступные способы приготовления для этого чая */
    brewMethods: BrewMethod[];

    /** Характеристики */
    characteristics: {
        /** Аромат/ароматы */
        aroma: string[];
        /** Вкус */
        flavor: string[];
        /** Послевкусие */
        aftertaste: string[];
        /** Внешний вид листа */
        appearance?: string[];
        /** Цвет настоя */
        liquorColor?: string;
    };

    /** Мета-данные */
    meta: {
        origin?: string;
        altitude?: number;
        harvestDate?: string;
        rating: number;
        favorite: boolean;
        addedDate: string;
    };

    /**
     * Сноска-предосторожность. Отсутствует у большинства чаёв — так и должно
     * быть, см. `TeaCaution`.
     */
    caution?: TeaCaution;
}

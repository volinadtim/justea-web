/**
 * Что меняет вкус: изменение в заваривании и его последствие.
 *
 * **Имя `BrewMistake` и поле `fix` существовали несколько часов и убраны —
 * их опровергли те же данные, ради которых всё затевалось.** Я исходил из
 * того, что у ошибки есть исправление: «заливают кипятком» → «остудите до
 * 75 °C». Cao 2022 это измерил и опроверг: рекомендованная навеска Те Гуань
 * Инь различается **в 1,7 раза** между тем, кто пьёт чай редко (2,9 г/100 мл),
 * и тем, кто пьёт ежедневно (5,0), и **обе названы рекомендуемыми**. Горечь и
 * вяжущесть, непереносимые для одного, — ровно то, к чему привык другой.
 *
 * Значит возвращать не к чему, и поле `fix` утверждало бы норму, которой нет.
 * Осталась пара «что сделано иначе → что от этого меняется»; форму предложили
 * justea-sources, и она честнее моей.
 *
 * Параметры заваривания читатель и так видит выше, в панели способа. Задача
 * этого блока — объяснить связь, а не повторить числа.
 *
 * **Связка «изменение → последствие» нигде не опубликована как таковая.**
 * justea-sources искали целенаправленно: есть нормативные имена дефектов
 * (GB/T 14487), измеренная химия (Jin 2019, Cao 2022) и потребительская
 * приемлемость (Cao 2022), а связка между ними — наш вывод. Отсюда поле
 * `confidence` и правило: `high` без источников не бывает, это проверяется.
 *
 * **Хранится на уровне категории по стандарту, а не сорта** (наблюдение
 * justea-voice, подтверждено измерением: у белого, зелёного и чёрного
 * оптимумы противоположные). Уровень `all` — для того, что не зависит от
 * категории вовсе: навеска в обе стороны и вода. Заводить их шесть раз
 * значило бы завести шесть мест для одной правки.
 *
 * **Про подстановки.** В `consequence` можно писать `{temperature}` и
 * `{ratio}` — они разворачиваются в числа **этого** сорта
 * (`lib/tea-type-facts.ts`). Одинаковый текст на восьми страницах не помогает
 * ранжированию ни одной из них, а блок существует ровно затем, чтобы
 * страница сорта отвечала на «<сорт> эффект».
 */
export interface BrewOutcome {
    /**
     * Устойчивый идентификатор записи уровня категории:
     * `"brew/all/too-much-leaf"`. Совпадает с `id` в `brew-mistakes.json` у
     * justea-sources. На него ссылается `replaces`.
     */
    id?: string;
    /**
     * Идентификатор записи категории, которую эта сортовая запись отменяет.
     *
     * Одна строка на запись. У гёкуро инвертируются и навеска, и
     * температура — это две записи, каждая со своим `replaces`, а не одна с
     * массивом: двух способов записать одно и то же быть не должно.
     *
     * Валидатор падает на ссылке в пустоту: иначе отменяемое правило молча
     * осталось бы рядом с отменяющим.
     */
    replaces?: string;
    /**
     * Что сделано иначе: «Больше листа», «Горячее», «Дольше».
     *
     * Нейтрально и без нормы. «Листа больше, **чем нужно**» вернуло бы ту
     * самую норму, которой по Cao 2022 нет.
     */
    change: string;
    /**
     * Что от этого меняется — словами и числами источника.
     *
     * На странице стоит после `change` отдельным предложением, поэтому **с
     * заглавной буквы**; проверяется.
     */
    consequence: string;
    /** Идентификаторы источников из `docs/sources/catalog.json`. */
    sources?: string[];
    /**
     * `high` — измерено напрямую и подтверждено источником; `medium` — есть
     * источник, но он слабее; `derived` — наш вывод из измеренного.
     *
     * Различие не формальное. Если `derived` ничем не отличается от `high`,
     * мы возвращаем себе жанр, от которого весь проект уходит. В разметку не
     * идёт ничего из этого блока вовсе, а читателю разницу передаёт сама
     * формулировка: «что меняется», а не «доказано, что».
     */
    confidence?: "high" | "medium" | "derived";
}

/**
 * Расхожее утверждение о чае, которое не подтверждается источниками.
 *
 * **Это НЕ то же самое, что `BrewOutcome`, и путаница здесь уже случилась.**
 * Я назвал поле `commonMistakes` и описал его как ошибки заваривания;
 * justea-sources прочитали название иначе и собрали четырнадцать записей вида
 * «бывает рассыпной шэн-пуэр» → «по GB/T 22111 не бывает». Обе вещи нужны, но
 * это разные блоки: один про то, что меняет вкус, другой про то, во что
 * читатель верит. Смешать их в одном разделе — получить текст, где рядом
 * стоят «больше листа — настой крепче» и «Бин Дао из Линьцана, а не из
 * Сишуанбаньны».
 *
 * Поэтому два поля с разными именами, и `commonMistakes` не используется
 * нигде: имя оказалось двусмысленным и выброшено.
 *
 * Формат — предложение justea-sources (`schema-proposal.md` §12) без правок.
 * Источник обязателен: «это миф» без ссылки — такое же неподтверждённое
 * утверждение, как и сам миф, только с обратным знаком.
 */
export interface Misconception {
    /** Расхожее утверждение, как его обычно формулируют. */
    claim: string;
    /** Что на самом деле, одним-двумя предложениями. */
    correction: string;
    /** Идентификаторы источников. Обязательны. */
    sources: string[];
    kind: "classification" | "origin" | "processing" | "composition" | "brewing";
}

/**
 * Короткая статичная сноска-предосторожность.
 *
 * Решение пользователя 06.11.2026: о пользе и вреде чая не пишем вовсе
 * (раздел `/health` снят целиком), вместо этого — одна фраза у тех чаёв, где
 * она обоснована источником уровня A или B. Пусто там, где обоснования нет;
 * выдумывать повод нельзя, поэтому из восьми чаёв каталога сноска обоснована
 * у двух.
 *
 * Поле принадлежит чаю, а не способу заваривания: предосторожность относится
 * к листу, а не к тому, как его залили.
 *
 * **В структурированные данные не выводится, и это решение, а не
 * недоработка** (принято 07.11.2026). У `Product` и `HowTo` нет поля со
 * значением «предосторожность», а натягивать её на `additionalProperty` — то
 * же искажение типов, из-за которого `meta.origin` не идёт в
 * `countryOfOrigin`. Главное же: JSON-LD усиливает то, что в него попадает, и
 * вынести сноску в разметку значило бы просить поисковик показать её в
 * сниппете — прямо против решения «о здоровье не пишем». Правило соответствия
 * работает в одну сторону: разметка не должна заявлять больше, чем видно;
 * видимый контент без разметки — нормально.
 */
export interface TeaCaution {
    /** Одно предложение. Без медицинских утверждений и без дозировок. */
    text: string;
    /**
     * Идентификаторы источников из `docs/sources/catalog.json` (ключи объекта
     * `sources`). Сноска о здоровье без прослеживаемого источника — ровно то,
     * что в проекте убирается, поэтому поле обязательное и непустое.
     * На странице не отображается: читателю нужен текст, а не ключ `efsa-…`.
     */
    sources: string[];
    /** Уровень обоснованности источника по шкале justea-sources. */
    level?: "A" | "B";
    /** Чем именно обосновано — для ревью, не для показа. */
    basis?: string;
}


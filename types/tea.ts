export interface BrewMethod {
    id: string;
    name: string;
    type: BrewMethodType;
    description: string;
    /**
     * Граммы чая на 100 мл воды.
     *
     * **Необязательно с 07.11.2026 — ровно для `type: "whisked"`,** и по той
     * же причине, по которой необязателен `infusions`: у взбивания нет
     * величины, которую это поле могло бы назвать. У матчи навесок две, и
     * они расходятся более чем в пять раз — 2,4 г/100 мл у усучи против 13,3
     * у коичи, — а поле одно. **Любое число здесь неверно для одного из двух
     * стилей.**
     *
     * Пока поле было обязательным, в него положили 2,4 — и оно протекло в
     * три места: в подстановку `{ratio}`, в мета-описание и в
     * `HowToSupply`. То есть в сниппете выдачи стояло число, неверное для
     * коичи. Обязательное поле, у которого не бывает правильного значения, —
     * приглашение положить туда хоть что-нибудь.
     *
     * Количества взбивания живут в `whisked[].powder` и `water`, где у
     * каждого стиля своё. У всех прочих способов поле обязано быть — это
     * проверяется, как и у `infusions`.
     */
    ratio?: number;
    temperature: Range;
    /**
     * Последовательные извлечения одного листа, время в секундах.
     *
     * **Имя не идеально, и это осознанный выбор, а не недосмотр.** У
     * проливного способа запись — это заливка, у варки (`type: "boiled"`) —
     * отдельная варка того же листа: DB53/T 236 п. 6.2.7 описывает именно
     * последовательность, первая 30–60 с, дальше от минуты. Вещи разные, имя
     * одно.
     *
     * Завести рядом второе поле `boils` было бы ровно той ошибкой, которую
     * justea-sources описали в `naming-traps.md`: от путаницы похожих имён
     * спасает не добавление ещё одного имени, а единственность. Структурно
     * это одно и то же — упорядоченный список извлечений со временем, — и
     * расходятся они только в том, как **называются на странице**. Поэтому
     * различие сделано там, где оно видно: `brewMethodHowTo` пишет «Варка 2»
     * вместо «Пролив 2», а `yield` — «3 варки» вместо «3 пролива».
     *
     * **Необязательно** ровно для `type: "whisked"`, у которого извлечений
     * нет ни одного. У всех прочих способов поле обязано быть непустым:
     * `HowTo` собирается отсюда, и способ без шагов — инструкция, которая не
     * инструктирует, то есть хуже отсутствия разметки.
     */
    infusions?: {
        number: number;
        time: number;
        notes?: string;
    }[];
    /**
     * Промывка листа перед первым извлечением — 醒茶, «пробуждение чая».
     * Нормативна для пуэра (DB53/T 236 п. 5.2.7).
     *
     * **Почему отдельное поле, а не первая запись в `infusions`.** Разбор
     * justea-catalog, и он точный: `infusions` — это то, что пьют. Положив
     * промывку туда, мы бы назвали сливаемый настой проливом, превратили
     * восемь проливов в девять и в таблице, и в `yield`, а у варки ещё и
     * упёрлись бы в проверку.
     *
     * **В `yield` не входит** — промывка не даёт чашки. В `totalTime` входит:
     * время на неё тратится.
     *
     * В разметке это отдельный `HowToStep` перед проливами. Соответственно и
     * на странице она должна быть видна — иначе разметка заявит шаг, которого
     * читатель не видит.
     */
    rinse?: {
        /** Сколько раз ополоснуть: обычно один-два. */
        count: number | Range;
        /**
         * Секунды.
         *
         * **Чаще всего поля нет, и это не пробел.** Единственный нормативный
         * источник на промывку — DB53/T 236 п. 5.2.7, и он говорит
         * «немедленно слить», секунд не задавая вовсе. Привычные «5–10 с»
         * источника не имеют.
         */
        time?: number;
        /** Уточнение словами источника. */
        note?: string;
        /**
         * Идентификаторы источников.
         *
         * Здесь они важнее обычного: **стандарт, которым промывка
         * закреплена, отменён 29.01.2026.** Формулировать надо «до 2026 года
         * было закреплено местным стандартом Юньнани», а не «по стандарту
         * промывают», и без ссылки эту разницу не удержать.
         */
        sources?: string[];
        confidence?: "high" | "medium" | "derived";
    };
    /**
     * Параметры взбивания — для `type: "whisked"`. Взаимоисключимо с
     * `infusions`.
     *
     * Массив, потому что у матчи два стиля с разными параметрами (усуча и
     * коича), и это один чай, а не два.
     */
    whisked?: WhiskedPreparation[];
    /** Особые заметки по приготовлению */
    notes?: string[];
}

export interface Tea {
    id: string;
    slug: string;
    name: string;
    photo?: string;
    description?: string;
    type: TeaType;

    /**
     * Категория по стандарту, если она расходится с ожидаемой для `type`.
     * Не влияет на URL и фильтры — см. `StandardTeaCategory`.
     */
    standardCategory?: StandardTeaCategory;

    /**
     * Сорт **куста**: «台茶12號», «Camellia sinensis var. assamica».
     *
     * ⚠️ **Пара для `naming-traps`, и по-русски обе называются «сорт».**
     * `cultivar` — это сорт растения; `slug` и `name` — сорт чая в обиходном
     * смысле, то есть продукт. Один куст даёт разные чаи: из Цзинь Сюаня
     * делают и баочжун, и красный чай, и габа-чай.
     *
     * У молочного улуна это суть записи, а не украшение: «молочный улун» —
     * торговое имя, 台茶12號 — сорт куста, и смешение этих двух смыслов
     * и есть то заблуждение, которое страница должна снять.
     *
     * Сейчас сорт куста живёт в `description` текстом; поле вынимает его
     * оттуда, чтобы на него можно было сослаться и показать отдельно.
     */
    cultivar?: string;

    /** Подтип пуэра. Осмысленно только при `type: "pu-erh"`. */
    puerhKind?: PuerhKind;

    /**
     * Модификация обработки. Не заменяет `type` и не влияет на маршрут:
     * габа-улун остаётся улуном и живёт на `/tea/oolong`. Хаб габа-чая —
     * `/guides/gaba`, а не страница типа (`docs/seo/site-structure.md` §4.6).
     */
    processing?: TeaProcessing;

    /**
     * Форма прессовки; отсутствие поля означает рассыпной чай.
     * При `puerhKind: "sheng"` обязательна — см. `PressedForm`.
     */
    pressedForm?: PressedForm;

    /**
     * Народные и ошибочные написания названия: «шен пуэр» при основном «шэн
     * пуэр», «гекуро» при «гёкуро», «оолонг» при «улун».
     *
     * Нужны потому, что частотнее часто именно неверное написание: «шен
     * пуэр» — 10 882 показа в месяц против 1 621 у «шэн пуэра», то есть в
     * 6,7 раза. Поиск по сайту ищет и по ним (`lib/search.ts`), чтобы человек
     * находил чай так, как он его называет. В тексты и заголовки синонимы не
     * подставляются: подмешивать варианты написания в видимый текст ради
     * поиска — это переоптимизация, за которую страницы и понижают.
     */
    synonyms?: string[];

    /**
     * Основной способ приготовления (для отображения в списке).
     *
     * Необязателен вместе с `brewMethods`: если способов нет, выбирать не из
     * чего.
     */
    primaryBrewMethod?: BrewMethodType;

    /**
     * Способы приготовления. **Может не быть ни одного, и это нормальное
     * состояние записи, а не черновик.**
     *
     * До 07.11.2026 валидатор требовал хотя бы один способ. Требование
     * выглядело безобидным — чай же как-то заваривают, — а работало так:
     * когда источника на параметры нет, заполнить поле всё равно нужно, и
     * человек кладёт туда самое правдоподобное из доступного. У семи чаёв
     * этим оказался **метод ISO 3103** — шесть минут кипятком, то есть
     * процедура дегустационной экспертизы, выданная за рецепт. Нашёл
     * justea-catalog, проверив опытом: убрал способ у Дянь Хуна и получил
     * падение «нет ни одного brewMethod».
     *
     * Правило, которое из этого следует: **валидатор, требующий полноты там,
     * где данных нет, не защищает данные, а производит догадки.** Прежде чем
     * делать поле обязательным, стоит спросить, что положит туда человек без
     * источника.
     *
     * Это тот же класс, что `ratio` у взбивания, только с другой стороны:
     * там поле было бессмысленным, здесь — обязательным.
     *
     * На странице у такого чая блок заваривания не показывается, а вместо
     * него стоит прямая фраза, что проверенных параметров пока нет: молчание
     * на месте главного блока выглядит поломкой.
     */
    brewMethods?: BrewMethod[];

    /** Характеристики */
    characteristics: {
        /** Аромат/ароматы */
        aroma: string[];
        /** Вкус */
        flavor: string[];
        /** Послевкусие */
        aftertaste: string[];
        /** Внешний вид листа */
        appearance?: string[];
        /** Цвет настоя */
        liquorColor?: string;
    };

    /**
     * Человеческий текст по характеристикам — рядом с массивами дескрипторов.
     *
     * Дескрипторы отвечают на «какой он», связный текст — на «чего ждать от
     * чашки». Одно другого не заменяет: список слов нельзя прочитать, а из
     * абзаца нельзя собрать `PropertyValue`.
     *
     * В разметку не выводится: `Product.additionalProperty` собирается из
     * дескрипторов, и дублировать то же прозой значило бы заявить одно
     * дважды.
     */
    characteristicsText?: string;

    /**
     * Фраза на месте блока параметров — для чая, у которого способов
     * заваривания нет.
     *
     * Пишет justea-voice, и она **про сам чай**, а не про нас: «Тёмный чай не
     * боится ни кипятка, ни долгого настаивания». Общая фраза «мы не нашли
     * источника» сообщает читателю габа-чая только то, что мы чего-то не
     * знаем, — она осталась запасной на случай, если своей для чая нет.
     */
    noBrewParamsNote?: string;

    /** Мета-данные */
    meta: {
        origin?: string;
        /**
         * Высота, метры. Диапазоном — когда источник даёт зону, а не точку:
         * у пуэров это 1000–2100 м, и под одно число такой факт не ложится,
         * поэтому поле стояло пустым там, где источник как раз есть.
         *
         * Форма та же, что у `BrewMethod.temperature`, — `Range`, одно имя
         * на проект.
         */
        altitude?: number | Range;
        harvestDate?: string;
        rating: number;
        favorite: boolean;
        addedDate: string;
    };

    /**
     * Сноска-предосторожность. Отсутствует у большинства чаёв — так и должно
     * быть, см. `TeaCaution`.
     */
    caution?: TeaCaution;

    /**
     * Что меняет вкус **именно у этого сорта**. Общее для категории лежит в
     * `data/tea-types.json` и подставляется автоматически — сюда писать его
     * не нужно, иначе на странице оно удвоится.
     */
    brewOutcomes?: BrewOutcome[];

    /**
     * Заблуждения об этом сорте. Общие для типа — в `data/tea-types.json`.
     */
    misconceptions?: Misconception[];
}

/**
 * Ошибка заваривания и её последствие.
 *
 * Отвечает на интент, который justea-voice вытащил из ядра: самая частая
 * уточнённая форма со словом «эффект» — «да хун пао эффект как заваривать».
 * Человек ищет «эффект», когда его чашка не совпала с ожиданием: он уже
 * знает, что должно было получиться, и ему нужно объяснение, **почему вышло
 * другое**. Описание вкуса такому читателю не помогает.
 *
 * **Рамка: блок не утверждает «вы заварили неправильно», и это не вежливость,
 * а следствие измерения.** По Cao 2022 рекомендованная навеска Те Гуань Инь
 * различается **в 1,7 раза** между тем, кто пьёт чай редко (2,9 г/100 мл), и
 * тем, кто пьёт ежедневно (5,0 г/100 мл), — и обе величины названы
 * рекомендуемыми. Горечь и вяжущесть, непереносимые для одного, — ровно то,
 * к чему привык другой. Поэтому `mistake` читается как «что обычно это
 * даёт», а не «что вы сделали не так», и на странице порядок именно такой:
 * сначала результат, потом причина.
 *
 * **Связка «ошибка → дефект» нигде не опубликована как таковая** — её нет ни
 * в одном источнике, justea-sources искали целенаправленно. Есть три разные
 * вещи: нормативные имена дефектов (GB/T 14487), измеренные изменения состава
 * (Jin 2019, Cao 2022) и потребительская приемлемость (Cao 2022). Связка
 * между ними — вывод, помеченный у них `confidence: derived`. Вывод прочный,
 * но **в разметку он не идёт и за цитату не выдаётся**; отсюда же поле
 * `confidence` ниже.
 *
 * **Хранится на уровне категории по стандарту, а не сорта** (наблюдение
 * voice, подтверждено измерением sources: у белого, зелёного и чёрного
 * оптимумы противоположные, сортовых исключений пять на шестнадцать чаёв).
 * Сортовые записи в `Tea.brewMistakes` добавляют только то, где сорт
 * действительно ведёт себя иначе.
 *
 * **Про подстановку — это важно для SEO.** Текст уровня типа одинаков на всех
 * страницах сортов этого типа, а блок существует ровно затем, чтобы страница
 * сорта отвечала на «<сорт> эффект». Одинаковый блок на восьми страницах не
 * помогает ни одной из них. Поэтому в `result` и `fix` можно писать
 * подстановки `{temperature}` и `{ratio}`: они разворачиваются в числа
 * **этого** сорта из его основного способа заваривания (см.
 * `lib/tea-type-facts.ts`). Так один хранимый текст даёт на каждой странице
 * свои числа, а не копию соседней.
 */
export interface BrewMistake {
    /**
     * Устойчивый идентификатор записи уровня категории: `"too-much-leaf"`.
     * Совпадает с `id` в `brewing-errors.json` у justea-sources.
     *
     * Нужен затем, чтобы сортовая запись могла **отменить** эту —
     * см. `replaces`. У сортовых записей обычно не нужен.
     */
    id?: string;
    /**
     * Идентификатор записи уровня категории, которую эта сортовая запись
     * отменяет.
     *
     * Без этого поля сборка была бы только складывающей, и на странице гёкуро
     * встали бы рядом «листа больше, чем нужно → горечь» и «официальная
     * навеска 16,7 г/100 мл», то есть правило и его прямое опровержение.
     * Исключения, которые прислали justea-sources, именно такого рода: у
     * гёкуро правило по навеске **инвертируется**, у ходзичи — правило про
     * второй пролив, у матчи «перестой» не определён вовсе.
     *
     * Валидатор падает, если `replaces` указывает на несуществующий `id`:
     * иначе отменяемое правило молча осталось бы на странице рядом с
     * отменяющим.
     */
    replaces?: string;
    /**
     * Что это обычно даёт: «заливают кипятком».
     *
     * Не «ваша ошибка»: см. про Cao 2022 выше. Формулировать как причину
     * наблюдаемого, а не как обвинение.
     */
    mistake: string;
    /**
     * Что получается: «настой горчит и вяжет».
     *
     * На странице стоит **первым** — человек ищет по симптому («почему чай
     * горчит», 206 показов), а не по действию.
     */
    result: string;
    /**
     * Что делать: «Остудите до {temperature}».
     *
     * **С заглавной буквы:** на странице три поля склеиваются в
     * «{result} — {mistake}. {fix}», то есть это отдельное предложение после
     * точки. Проверяется в `scripts/check-tea-data.mjs`.
     */
    fix: string;
    /** Идентификаторы источников из `docs/sources/catalog.json`. */
    sources?: string[];
    /**
     * `high` — измерено напрямую; `derived` — вывод из измеренного.
     *
     * Почти всё здесь будет `derived`: связки «ошибка → дефект» как таковой
     * не существует ни в одном источнике. Поле нужно для ревью и для того,
     * чтобы `derived` никогда не уехало в разметку как факт.
     */
    confidence?: "high" | "derived";
}

/**
 * Расхожее утверждение о чае, которое не подтверждается источниками.
 *
 * **Это НЕ то же самое, что `BrewMistake`, и путаница здесь уже случилась.**
 * Я назвал поле `commonMistakes` и описал его как ошибки заваривания
 * («заливают кипятком → горчит»); justea-sources прочитали название иначе и
 * собрали четырнадцать записей вида «бывает рассыпной шэн-пуэр» → «по
 * GB/T 22111 не бывает». Обе вещи нужны, но это разные блоки: один про то,
 * что читатель сделал, другой про то, во что он верит. Смешать их в одном
 * разделе — получить текст, где рядом стоят «остудите воду до 80 °C» и
 * «Бин Дао из Линьцана, а не из Сишуанбаньны».
 *
 * Поэтому два поля с разными именами, и `commonMistakes` не используется
 * нигде: имя оказалось двусмысленным и выброшено.
 *
 * Формат — предложение justea-sources (`schema-proposal.md` §12) без правок.
 * Источник обязателен: «это миф» без ссылки — такое же неподтверждённое
 * утверждение, как и сам миф, только с обратным знаком.
 */
export interface Misconception {
    /** Расхожее утверждение, как его обычно формулируют. */
    claim: string;
    /** Что на самом деле, одним-двумя предложениями. */
    correction: string;
    /** Идентификаторы источников. Обязательны. */
    sources: string[];
    kind: "classification" | "origin" | "processing" | "composition" | "brewing";
}

/**
 * Короткая статичная сноска-предосторожность.
 *
 * Решение пользователя 06.11.2026: о пользе и вреде чая не пишем вовсе
 * (раздел `/health` снят целиком), вместо этого — одна фраза у тех чаёв, где
 * она обоснована источником уровня A или B. Пусто там, где обоснования нет;
 * выдумывать повод нельзя, поэтому из восьми чаёв каталога сноска обоснована
 * у двух.
 *
 * Поле принадлежит чаю, а не способу заваривания: предосторожность относится
 * к листу, а не к тому, как его залили.
 *
 * **В структурированные данные не выводится, и это решение, а не
 * недоработка** (принято 07.11.2026). У `Product` и `HowTo` нет поля со
 * значением «предосторожность», а натягивать её на `additionalProperty` — то
 * же искажение типов, из-за которого `meta.origin` не идёт в
 * `countryOfOrigin`. Главное же: JSON-LD усиливает то, что в него попадает, и
 * вынести сноску в разметку значило бы просить поисковик показать её в
 * сниппете — прямо против решения «о здоровье не пишем». Правило соответствия
 * работает в одну сторону: разметка не должна заявлять больше, чем видно;
 * видимый контент без разметки — нормально.
 */
export interface TeaCaution {
    /** Одно предложение. Без медицинских утверждений и без дозировок. */
    text: string;
    /**
     * Идентификаторы источников из `docs/sources/catalog.json` (ключи объекта
     * `sources`). Сноска о здоровье без прослеживаемого источника — ровно то,
     * что в проекте убирается, поэтому поле обязательное и непустое.
     * На странице не отображается: читателю нужен текст, а не ключ `efsa-…`.
     */
    sources: string[];
    /** Уровень обоснованности источника по шкале justea-sources. */
    level?: "A" | "B";
    /** Чем именно обосновано — для ревью, не для показа. */
    basis?: string;
}


/**
 * Приготовление взбиванием — матча. Форма предложена justea-sources
 * (`schema-proposal-matcha.md`), принята без правок.
 *
 * Почему не `infusions`: пролива нет ни одного. Порошок взбивают, и он
 * остаётся во взвеси без осадка — это другая операция, а не заваривание с
 * одним коротким проливом.
 */
export interface WhiskedPreparation {
    /**
     * Усуча (薄茶, тонкий) или коича (濃茶, густой).
     *
     * Это **один и тот же продукт**, приготовленный по-разному: концентрация
     * отличается в 4–5 раз. Поэтому стиль — поле, а не два разных чая:
     * 2,4 и 13,3 г/100 мл не усредняются, но и разными чаями не являются.
     */
    style: "usucha" | "koicha";
    /** Навеска порошка, г. */
    powder: number | Range;
    /** Объём воды, мл. */
    water: number | Range;
    temperature: Range;
    /**
     * Взбивать до пены или вымешивать до однородной массы.
     *
     * Различие обязательное, а не стилистическое: в японском это **разные
     * глаголы** — усучу 点てる (взбивают), коичу 練る (вымешивают). У усучи
     * цель мелкая пена, у коичи густая масса **без пены**. Не различив их,
     * человек будет взбивать коичу венчиком и не получит нужной текстуры.
     */
    motion: "whisk" | "knead";
    /** Длительность, с — если источник её указывает. */
    duration?: number | Range;
    /** Целевой результат — словами источника. */
    target?: string;
    /** Просеивать ли порошок перед приготовлением. */
    sift?: boolean;
    tool?: "chasen" | "electric-frother" | "shaker";
}


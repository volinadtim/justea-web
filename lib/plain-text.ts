import { BrewMethod, Tea } from "@/types/tea";

/**
 * Ограждение справочного аппарата на выходе к читателю.
 *
 * Решение пользователя 07.11.2026: на странице нет номеров стандартов,
 * иероглифов, процентов, химии, фамилий исследователей и оборотов вида
 * «по стандарту» и «экспертная оценка». Аудитория — и новичок, который чая
 * раньше не встречал, и мастер; ни тому, ни другому это не нужно.
 *
 * Проверка стоит здесь, а не в данных, намеренно. Фактура и её основание
 * остаются в `data/**` и `docs/sources/**` — они не исчезают, они не
 * выводятся. Ограждение в поле, которое не доходит до читателя, —
 * не ограждение; поэтому фильтр живёт на последнем шаге, перед разметкой.
 *
 * Это временная мера для текстов, которые ещё не переписаны по-человечески:
 * строка с основанием прячется целиком, а вместе с ней — и оговорка
 * («навеска гунфу у пуэра практика, а не норма»). Оговорку надо вернуть
 * переписанным текстом, иначе практика будет читаться как норма.
 */
const APPARATUS = [
    /GB\s?\/?\s?T\s?\d/,
    /\bISO\b/,
    /\bDB\s?53\b/,
    /\bGOST\b|\bГОСТ\b/,
    /[　-鿿＀-￯]/, // иероглифы и китайская пунктуация
    /\d\s?%/,
    /полифенол|катехин|теанин|EGCG|аминокислот|\bppm\b|CaCO/i,
    // Фамилия и год: «Cao 2022». Только латиницей, намеренно. Год сам по
    // себе не аппарат — sources это проверил, и «способ придумали в 1987»
    // читателю ничего не ломает. Аппаратом его делает фамилия рядом, а
    // кириллица с годом чаще оказывается обычным текстом: «Тайвань 1980».
    /\b[A-Z][a-z]+\s+(?:19|20)\d\d\b/,
    /\bet al\b/i,
    /уровн[ьея]\s+[ABC]\b/,
    /экспертн|нормативн|по стандарт|стандарт\w*/i,
    // Ссылка на источник — тоже аппарат: «официальные параметры», названия
    // организаций и префектур, «совпадают у двух источников».
    /\bAssociation\b|\bInstitute\b|\bUniversity\b/i,
    /официальн\w*\s+(?:япон|китай|тайван|индий)\w*/i,
    /источник(?:ов|ах|а)\b|двух источник/i,
    /префектур\w*\s+[А-ЯA-Z]/,
];

/** Содержит ли строка справочный аппарат, которого не должно быть на странице. */
export function hasApparatus(text: string | null | undefined): boolean {
    if (!text) {
        return false;
    }

    return APPARATUS.some((pattern) => pattern.test(text));
}

/** Строки без аппарата, в исходном порядке. */
export function plainOnly(texts: readonly string[] | undefined): string[] {
    return (texts ?? []).filter((text) => !hasApparatus(text));
}

/**
 * Способы заваривания, очищенные ДО передачи клиенту.
 *
 * `TeaBrewSection` — клиентский компонент, и Next сериализует его пропсы в
 * страницу целиком. Пока фильтр стоял внутри компонента, читатель номеров
 * стандартов не видел, а в исходнике страницы они лежали: «DB53/T 236-2007»
 * и «GB/T 23776» уезжали клиенту на семи страницах, включая главную. Нашёл
 * justea-catalog.
 *
 * Ограждение на выходе к читателю — не ограждение на границе данных. Это
 * второе: строки с аппаратом не доезжают до пропсов вообще, поэтому их нет
 * ни на экране, ни в исходнике, ни в индексе краулера.
 *
 * `sources` и `confidence` у промывки снимаются целиком: это основание, оно
 * нужно в `data/**`, а на клиенте ему делать нечего.
 */
const INTERNAL_FIELDS = ["reviewNote"] as const satisfies readonly (keyof BrewMethod)[];

export function plainBrewMethods(methods: readonly BrewMethod[]): BrewMethod[] {
    return methods.map((method) => {
        const { rinse, infusions, whisked, ...rest } = method;

        // Поля, которых у читателя нет вовсе: они существуют для нас.
        // Снимаются здесь, на единственной границе, через которую способы
        // заваривания уходят и в пропсы клиента, и в разметку. Новое
        // внутреннее поле добавлять сюда же — и проверка по собранным
        // страницам поймает, если о нём забудут.
        for (const field of INTERNAL_FIELDS) {
            delete rest[field];
        }

        return {
            ...rest,
            // Цель взбивания («мелкопузырчатая пена») аппарата сейчас не
            // содержит, но это такая же строка из данных, как заметка, и
            // уезжает она в те же два места: в пропсы клиента и в
            // `HowToStep`. Поле, которое ограждение пропускает, рано или
            // поздно окажется единственным, где аппарат остался.
            ...(whisked
                ? {
                      whisked: whisked.map((preparation) => ({
                          ...preparation,
                          target: hasApparatus(preparation.target)
                              ? undefined
                              : preparation.target,
                      })),
                  }
                : {}),
            ...(hasApparatus(method.description) ? { description: undefined } : {}),
            notes: plainOnly(method.notes),
            ...(rinse
                ? {
                      rinse: {
                          ...rinse,
                          note: hasApparatus(rinse.note) ? undefined : rinse.note,
                          sources: undefined,
                          confidence: undefined,
                      },
                  }
                : {}),
            ...(infusions
                ? {
                      infusions: infusions.map((infusion) => ({
                          ...infusion,
                          // У пролива `notes` — одна строка, не список.
                          notes: hasApparatus(infusion.notes)
                              ? undefined
                              : infusion.notes,
                      })),
                  }
                : {}),
        } as BrewMethod;
    });
}

/**
 * Поля, которые карточке чая нужны, и ничего кроме них.
 *
 * `TeaCard` — клиентский компонент, и до этой правки в него передавалась
 * вся запись чая целиком. Next сериализует пропсы в страницу, поэтому
 * каталог уезжал клиенту со всем, что в записях есть: заметки с номерами
 * стандартов, основания промывки, `caution.basis`. На главной — все
 * двадцать четыре записи сразу.
 *
 * Поэтому здесь не фильтр, а проекция: перечислены поля, которые карточка
 * выводит. Новое поле в записи чая само на клиент не попадёт.
 */
export type TeaCardData = {
    id: string;
    slug: string;
    name: string;
    type: string;
    description?: string;
    liquorColor?: string;
};

export function toTeaCardData(tea: Tea): TeaCardData {
    return {
        id: tea.id,
        slug: tea.slug,
        name: tea.name,
        type: tea.type,
        description: tea.description,
        liquorColor: tea.characteristics.liquorColor,
    };
}


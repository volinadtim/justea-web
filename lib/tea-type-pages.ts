/** Короткая подпись типа для крошек и ссылок. */
export function teaTypeLabel(type: TeaType): string {
    return TEA_TYPE_LABELS[type];
}

/** Путь страницы типа. Единая точка правды для ссылок, sitemap и редиректов. */
export function teaTypePath(type: TeaType): string {
    return `/tea/${type}`;
}

export function isKnownTeaTypePage(value: string): value is TeaType {
    return (TEA_TYPES as string[]).includes(value);
}

/**
 * Числа в русском тексте.
 *
 * Десятичный разделитель в русском — запятая. «16.7 г» читается как опечатка
 * или как машинный вывод, и на странице чая это особенно заметно: навеска
 * стоит в самом видном месте.
 *
 * Функция одна на проект намеренно. Форматирование навески жило в четырёх
 * местах независимо — в подстановке `{ratio}`, в мета-описании, в разметке и
 * в панели заваривания, — и точка вместо запятой была во всех четырёх.
 * Четыре копии одной строки означают четыре места, где её чинить.
 */

/** `16.7` → `«16,7»`, `3` → `«3»`. */
export function formatDecimal(value: number): string {
    return String(value).replace(".", ",");
}

/** `3.5` → `«3,5 г на 100 мл»`. */
export function formatRatio(ratio: number): string {
    return `${formatDecimal(ratio)} г на 100 мл`;
}

/**
 * ПРЕДЛОЖЕНИЕ, не проверка. Пять правил регистра здоровья и применение
 * телесных дескрипторов к прозе — в виде кода, чтобы оркестратору не
 * собирать их по памяти (ровно за это мы платили весь день).
 *
 * Переносится в `scripts/check-tea-data.mjs`, после чего ЭТОТ ФАЙЛ УДАЛЯЕТСЯ.
 * Держать его рядом с рабочей проверкой нельзя: одно правило в двух местах
 * расходится молча.
 *
 * Прогон: node docs/catalog/health-register-proposal.mjs
 * Порядок проверки — по данным, потом по подброшенным нарушениям, потом по
 * вспомненным фразам. И всё это в JavaScript: justea-sources проверили свою
 * версию в Python, где `\b` знает кириллицу, получили зелёный результат и
 * обнаружили в JS не ложное срабатывание, а молчание. Поэтому ниже нигде нет
 * `\b` — только явные просмотры вперёд и назад.
 */

import { readFileSync } from "node:fs";

const W = "(?<![а-яёa-z])";
const stem = (s) => new RegExp(W + s, "i");

/** Слова, которые сами по себе о пользе. Как в scripts, без изменений. */
export const HEALTH_CLAIMS = stem("(?:польз|вред|бодрит|тонизир|успокаива|иммунит|похуд|оздоров)");

/** Названия состояний. Два берутся корнем: других форм у них в деле нет. */
export const CONDITION_PLAIN = stem("(?:целебн|тревог)");

/**
 * Сон. Четыре короткие формы — полные слова, и им нужна граница СПРАВА:
 * без неё «сна» ловит «сначала», «снаружи», «снаряжение», и «сначала»
 * стоит в данных сегодня (гёкуро, заметка способа). «бессонниц» и «сонлив» —
 * корни, границы справа им не нужно; «сонлив» добавлен потому, что граница
 * справа выключает «сонливость» у формы «сон».
 */
export const SLEEP = new RegExp(
    `${W}(?:(?:сна|сну|сном|сон)(?![а-яё])|бессонниц|сонлив)`,
    "i",
);

/** Пара «слово + предмет рядом», окно в символах. */
const near = (text, a, b, window = 40) => {
    const left = [...text.matchAll(a)];
    const right = [...text.matchAll(b)];
    return left.some((x) => right.some((y) => Math.abs(x.index - y.index) <= window));
};

const BODY_PARTS = /(?:организм|кишечник|кров|печен|шлак|токсин)[а-яё]*/gi;

/** Очищение. Пара нужна: «очищенная вода» законна и стоит в выгрузке. */
export const cleansing = (text) => near(text, /очищ[а-яё]*/gi, BODY_PARTS);

/** Давление. Пара: либо «артериальное/кровяное», либо глагол изменения. */
export const pressure = (text) =>
    near(text, /давлен[а-яё]*/gi, /(?:артериальн|кровян|снижа|понижа|повыша)[а-яё]*/gi);

/** Энергия. Корень производственный («энергозатраты»), поэтому только фразы. */
export const energy = /заряд энергии|да[ёе]т энергию|прилив сил/i;

/** Одиннадцать нормативных терминов justea-sources, формы из поля `ru`. */
export const NORMATIVE = (() => {
    const file = JSON.parse(readFileSync("docs/sources/sensory-terms-normative.json", "utf8"));
    return (file.exclude_normative ?? []).flatMap((item) =>
        String(item.ru)
            .split("/")
            .map((form) => form.replace(/\(.*?\)/g, "").trim().toLowerCase())
            .filter(Boolean),
    );
})();

/**
 * Телесные дескрипторы в связной прозе.
 *
 * Пар две, и это измерено, а не выбрано. justea-sources предложили
 * исключением свой список нормативных терминов — он инертен: ни одна из
 * одиннадцати записей не содержит ни «согрева», ни «охлажда», ни «расслабл».
 * Я предложил обратную пару (срабатывать, если рядом НЕТ посуды) — она
 * теряет смешанное предложение «Чай согревает изнутри, заваривайте его
 * кипятком»: посуда гасит обещание. Прямая пара (срабатывать, если рядом
 * ЕСТЬ слово о человеке) теряет голые обещания «Этот чай согревает».
 *
 * Объединение даёт ноль и ноль, потому что пары промахиваются на РАЗНЫХ
 * классах: смешанное предложение содержит телесное слово, голое обещание не
 * содержит посуды. Нашли это, только когда каждый прогнал пару другого —
 * свой набор каждый подобрал под свою идею.
 *
 * Цена остаётся названной: «Чай согревает, как чашка бульона» промолчит —
 * «чашка» гасит, телесного слова нет. Правка ради одной фразы не стоит
 * усложнения, но молчание здесь надо знать.
 */
const BODY_STEMS = /(?:согрева|охлажда|расслабл)[а-яё]*/gi;
const PERSON = /(?:организм|тело|изнутри|человек|нерв|усталост|стресс|настроен)[а-яё]*/gi;
const VESSEL = /(?:чайник|посуд|гайван|чашк|настои|настой|вод|лист|кипят|термос|холодильник)[а-яё]*/gi;

export const bodyInProse = (text) => {
    if (!/(?:согрева|охлажда|расслабл)/i.test(text)) return false;
    if (near(text, BODY_STEMS, PERSON, 50)) return true;
    return !near(text, BODY_STEMS, VESSEL, 50);
};

/* ------------------------------- прогон ------------------------------- */

const RULES = [
    ["health", (t) => HEALTH_CLAIMS.test(t)],
    ["состояние", (t) => CONDITION_PLAIN.test(t)],
    ["сон", (t) => SLEEP.test(t)],
    ["очищение", cleansing],
    ["давление", pressure],
    ["энергия", (t) => energy.test(t)],
    ["телесное в прозе", bodyInProse],
];

const hit = (text) => RULES.filter(([, test]) => test(text)).map(([name]) => name);

let strings = 0;
const onData = [];

for (const file of ["data/teas.json", "data/tea-types.json"]) {
    const walk = (node) => {
        if (typeof node === "string") {
            strings += 1;
            const names = hit(node);
            if (names.length) onData.push([names.join(","), node.slice(0, 80)]);
            return;
        }
        if (Array.isArray(node)) return node.forEach(walk);
        if (node && typeof node === "object") return Object.values(node).forEach(walk);
    };
    walk(JSON.parse(readFileSync(file, "utf8")));
}

console.log(`1. по данным: строк ${strings}, срабатываний ${onData.length}`);
for (const [names, text] of onData) console.log(`   [${names}] «${text}…»`);


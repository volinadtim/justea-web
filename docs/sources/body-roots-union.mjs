#!/usr/bin/env node
/*
 * Правило для «согрева», «охлажда», «расслабля» в связной прозе.
 *
 * Зачем объединение, а не одна пара. У justea-catalog в master стоит только
 * отрицательное условие: слово срабатывает, если рядом НЕТ посуды. Оно теряет
 * смешанные предложения, где обещание и инструкция стоят рядом, и посуда
 * гасит обещание. Прямая пара (срабатывает, если рядом ЕСТЬ слово о человеке)
 * теряет голые обещания без телесного слова.
 *
 * Пары промахиваются на РАЗНЫХ классах предложений, поэтому дешевле взять обе,
 * чем выбирать лучшую. Это было не видно ни ему, ни мне, пока каждый проверял
 * свою на своём наборе.
 *
 * \b здесь нет НИГДЕ и быть не должно: в JavaScript \w — латиница, и внутри
 * русского текста границы слова не существует. Образец с \b даёт не ложное
 * срабатывание, а молчание. Проверено: моя прошлая версия с \b ловила 1
 * обещание из 6. Предупреждение об этом стоит в самом check-tea-data.mjs.
 *
 * Запуск: node docs/sources/body-roots-union.mjs
 */

const WORD_START = "(?<![а-яёa-z])";
const ROOT = "(?:согрева|охлажда|расслабля)";

/** Посуда, вода, лист: рядом с ними слово описывает инструкцию. */
const VESSEL = "(?:чайник|чашк|гайван|посуд|вода|воду|водой|кипят|лист|настой|чахай|пиал)";

/** Человек и его обстоятельства: рядом с ними слово описывает обещание. */
const BODY =
    "(?:человек|тел[оа]|организм|в холод|зимой|изнутри|руки|душу|после|перед сном|вечером|устал)";

/** Рядом НЕТ посуды — значит подлежащее не предмет. */
const NO_VESSEL = new RegExp(
    `${WORD_START}${ROOT}\\w*(?![\\s\\S]{0,60}${VESSEL})(?<!${VESSEL}[\\s\\S]{0,60})`,
    "i",
);

/** Рядом ЕСТЬ слово о человеке — значит обещание, даже если рядом инструкция. */
const WITH_BODY = new RegExp(
    `${WORD_START}${ROOT}\\w*[\\s\\S]{0,60}${BODY}|${BODY}[\\s\\S]{0,60}${WORD_START}${ROOT}\\w*`,
    "i",
);

export function bodyPromiseHit(text) {
    const t = text ?? "";
    return NO_VESSEL.test(t) || WITH_BODY.test(t);
}

/* ---------- прогон ---------- */

const INSTRUCTIONS = [
    "Чайник согревают кипятком перед первым проливом",
    "Настой охлаждают до 10 °C и подают со льдом",
    "Прогретый чайник согревает лист равномерно",
    "Воду охлаждают переливанием из чашки в чашку",
    "Посуду согревают, чтобы настой не терял температуру",
];

const PROMISES = [
    "Чай согревает в холодный день",
    "Этот чай согревает",
    "Зелёный чай охлаждает организм",
    "Напиток расслабляет после тяжёлого дня",
    "Чай согревает изнутри, заваривайте его кипятком",
    "Пуэр согревает вечером",
];

const falsePositives = INSTRUCTIONS.filter(bodyPromiseHit);
const misses = PROMISES.filter((t) => !bodyPromiseHit(t));

console.log(`инструкций: ${INSTRUCTIONS.length}, ложных срабатываний: ${falsePositives.length}`);
falsePositives.forEach((t) => console.log("   ЛОВИТ ЗРЯ: " + t));
console.log(`обещаний: ${PROMISES.length}, пропусков: ${misses.length}`);
misses.forEach((t) => console.log("   ПРОПУСК:   " + t));

console.log("\nдля сравнения, по отдельности:");
console.log(
    `  только «нет посуды»:  ложных ${INSTRUCTIONS.filter((t) => NO_VESSEL.test(t)).length}, ` +
        `пропусков ${PROMISES.filter((t) => !NO_VESSEL.test(t)).length}`,
);
console.log(
    `  только «есть человек»: ложных ${INSTRUCTIONS.filter((t) => WITH_BODY.test(t)).length}, ` +
        `пропусков ${PROMISES.filter((t) => !WITH_BODY.test(t)).length}`,
);

console.log(
    "\nназванная цена, её не чиню: «Чай согревает, как чашка бульона» → " +
        (bodyPromiseHit("Чай согревает, как чашка бульона") ? "ловится" : "молчит") +
        " (чашка гасит, телесного слова нет)",
);

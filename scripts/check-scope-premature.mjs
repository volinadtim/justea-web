/**
 * ПРЕДЛОЖЕНИЕ для `scripts`: не стоит ли рамка `characteristicsScope` раньше
 * времени.
 *
 * Зачем. Рамка утверждает происхождение дескрипторов блока. Если блок ещё не
 * того состава, о котором она говорит, рамка врёт — и врать может в обе
 * стороны. Прошлая рамка Те Гуань Инь завышала обоснованность («орхидея,
 * сирень и мёд записаны именно для этого чая»), новая занизила бы, объявив те
 * же слова описанием улунов вообще.
 *
 * Два правила, которые мы с justea-voice перепробовали, и почему оба не годятся:
 *
 *  - моё, по форме текста: «не названы ни дескриптор, ни число — рамка
 *    независима». Пропускает ровно те две рамки, из которых выведено: они не
 *    называют ничего и всё равно верны только после снятия;
 *  - их, по данным: «каждый дескриптор блока покрыт профилем типа». Слишком
 *    строгое: у молочного улуна блок смешанный (четыре от типа и свой «лёгкий
 *    молочный»), а рамка верна, потому что называет, какие именно от типа.
 *
 * Проверка поэтому смотрит, ЧТО рамка утверждает, и сверяет это с данными:
 *
 *  - рамка называет дескрипторы → каждый названный должен быть в блоке и
 *    покрыт профилем типа;
 *  - рамка говорит о блоке целиком → каждый дескриптор блока должен быть
 *    покрыт профилем типа.
 *
 * ⚠ Покрытие здесь перечислено руками, и это не недоделка, а предел: в данных
 * нет поля происхождения у дескриптора (см. outbox #47 и #70). Как только
 * `characteristics` получит `sources`/`confidence`, этот список надо выбросить
 * и читать покрытие из записи. До тех пор список расходится с фактурой молча.
 *
 * Прогон: node docs/catalog/check-scope-premature.mjs
 *
 * Перенесено из `docs/catalog/` в `scripts/` без правок: одно правило в двух
 * местах расходится молча, и копия у автора удалена тем же коммитом.
 *
 * Проверка — сложение двух неверных правил, а не выбор между ними. «Рамка,
 * не называющая дескриптора и числа, независима» пропускала те самые две
 * рамки, из которых была выведена: они не называют ничего и всё равно верны
 * только после снятия. «Каждый дескриптор блока покрыт профилем типа»
 * забраковало бы молочный улун, где блок смешанный, а рамка верна именно
 * потому, что называет, какие слова от типа.
 *
 * Поэтому смотрим, что рамка УТВЕРЖДАЕТ, и сверяем с данными: называет
 * дескрипторы — каждый названный должен быть в блоке и покрыт; говорит о
 * блоке целиком — покрыт должен быть каждый.
 *
 * Проба с двумя отложенными рамками встроена нарочно: проверка, не ловящая
 * случай, из которого выведена, бесполезна, и это должно быть видно из её
 * вывода, а не из переписки.
 *
 * ПРЕДЕЛ, названный автором: покрытие перечислено руками, двадцать строк,
 * потому что происхождения у дескриптора в данных нет. Как только
 * `characteristics` получит `sources` и `confidence`, список выбрасывается и
 * покрытие читается из записи. Это третий раз, когда тот пробел стоит нам
 * чего-то конкретного.
 */

import { readFileSync } from "node:fs";

const teas = JSON.parse(readFileSync("data/teas.json", "utf8"));

const low = (s) => String(s).toLowerCase().replace(/ё/g, "е").replace(/й/g, "и");

/** Покрыто профилем ТИПА, поле к полю. Основания — в outbox #67 и #69. */
const BY_TYPE_PROFILE = new Set([
    "tie-guan-yin|цветочныи|аромат", "tie-guan-yin|сладкое|послевкусие",
    "da-hong-pao|сладкое|послевкусие",
    "milk-oolong|цветочныи|аромат", "milk-oolong|мягкии|вкус",
    "milk-oolong|округлыи|вкус", "milk-oolong|сладкое|послевкусие",
    "lao-banzhang|чистыи|аромат", "lao-banzhang|густои|вкус",
    "yiwu|чистыи|аромат", "yiwu|густои|вкус",
    "bingdao|чистыи|аромат", "bingdao|густои|вкус",
    "menghai-shu|особыи выдержанныи|аромат", "menghai-shu|мягко-густои|вкус",
    "menghai-shu|возвращающаяся сладость|послевкусие",
    "tuocha|особыи выдержанныи|аромат", "tuocha|мягко-густои|вкус",
    "tuocha|возвращающаяся сладость|послевкусие",
]);

/** Все сенсорные слова каталога: нужны, чтобы заметить названное, но отсутствующее. */
const VOCABULARY = new Set();
for (const tea of teas) {
    const c = tea.characteristics;
    for (const d of [...(c.aroma ?? []), ...(c.flavor ?? []), ...(c.aftertaste ?? [])]) {
        VOCABULARY.add(low(d));
    }
}

/** Подтверждено как СВОЁ: источник говорит это про сам чай (outbox #67). */
const OWN = new Set([
    "gongting-puer|выдержанныи", "gongting-puer|насыщенныи", "gongting-puer|густои",
    "gongting-puer|мягкии", "gongting-puer|сладко-освежающии",
    "milk-oolong|легкии молочныи",
    "lapsang-souchong|сосновыи дым", "lapsang-souchong|сушеныи лонган",
    "gaba-tea|особыи чаиныи", "gaba-tea|сладковатыи", "gaba-tea|легкая терпкость",
    "dong-ding|обжарочныи",
    "liupao|выдержанныи", "liupao|густои", "liupao|мягкии",
]);

const root = (s) => low(s).replace(/(ость|ыи|ое|ии|ыми|ая|ую|ого|ом)$/, "");

/** Проверяет одну рамку против одного блока. Возвращает список нарушений. */
export function audit(slug, scope, block) {
    const bad = [];
    const text = low(scope);

    if (block.length === 0) {
        bad.push("блок пуст: рамке не о чем говорить");
        return bad;
    }

    const named = block.filter(([d]) => text.includes(root(d)));

    /* Названо слово, которого в блоке нет. Ловится по словарю дескрипторов
       каталога: «дымность» в рамке шу-пуэра — слово из словаря, но не из
       этого блока. */
    /* Корень из словаря каталога, упомянутый рамкой, должен иметь
       соответствие В ЭТОМ блоке. Сравниваем корни, а не слова: «цветочность»
       в рамке и «Цветочный» в блоке — одно и то же упоминание, а
       «дымность» в рамке шу-пуэра не отвечает ничему. */
    const blockRoots = new Set(block.map(([d]) => root(d)));
    for (const word of VOCABULARY) {
        const r = root(word);
        if (r.length < 4 || !text.includes(r)) continue;
        /* Вхождение одного корня в другой считается тем же упоминанием:
           «сладкое послевкусие» из словаря и «Сладкое» в блоке — одно
           слово, достроенное заголовком поля. */
        if ([...blockRoots].some((b) => b.includes(r) || r.includes(b))) continue;
        bad.push(`рамка называет «${word}», а в блоке такого слова нет`);
    }

    if (named.length === 0) {
        for (const [d, field] of block) {
            if (!BY_TYPE_PROFILE.has(`${slug}|${low(d)}|${field}`)) {
                bad.push(`рамка о блоке целиком, а «${d}» (${field}) профилем типа не покрыт`);
            }
        }
        return bad;
    }

    for (const [d, field] of named) {
        if (!BY_TYPE_PROFILE.has(`${slug}|${low(d)}|${field}`)) {
            bad.push(`названный «${d}» (${field}) профилем типа не покрыт`);
        }
    }

    /* Вторая половина требования, названная justea-voice: перечисление
       делит блок, и читатель достроит, что НЕ названное — своё. Значит
       каждое не названное обязано быть подтверждённым своим. */
    for (const [d, field] of block) {
        if (named.some(([n]) => n === d)) continue;
        if (!OWN.has(`${slug}|${low(d)}`)) {
            bad.push(
                `«${d}» (${field}) не назван рамкой, и своим не подтверждён: ` +
                    "читатель прочтёт его как свойство сорта",
            );
        }
    }

    return bad;
}

const blockOf = (tea) => {
    const c = tea.characteristics;
    return [
        ...(c.aroma ?? []).map((d) => [d, "аромат"]),
        ...(c.flavor ?? []).map((d) => [d, "вкус"]),
        ...(c.aftertaste ?? []).map((d) => [d, "послевкусие"]),
    ];
};

const problems = [];
let checked = 0;

for (const tea of teas) {
    if (!tea.characteristicsScope) continue;
    checked += 1;
    for (const line of audit(tea.slug, tea.characteristicsScope, blockOf(tea))) {
        problems.push(`${tea.slug}: ${line}`);
    }
}

console.log(`рамок проверено: ${checked}`);

if (problems.length > 0) {
    console.error(`преждевременных рамок: ${problems.length}`);
    for (const line of problems) console.error(`  ${line}`);
    process.exitCode = 1;
} else {
    console.log("✅ ни одна рамка не опережает состав своего блока");
}

/* Пробы. Проверка, не ловящая случай, из которого выведена, бесполезна, а
   предел, записанный в комментарии, проверяется один раз. Поэтому и то и
   другое лежит здесь и прогоняется каждый раз. Пробы 1–4 предложены
   justea-voice. */
const PROBES = [
    ["отложенная рамка Те Гуань Инь", "tie-guan-yin", "Так описывают улуны вообще.", true],
    ["отложенная рамка Да Хун Пао", "da-hong-pao", "Так описывают улуны вообще.", true],
    ["проба 1: названо слово не из блока", "menghai-shu", "Дымность есть у шу-пуэров вообще.", true],
    ["проба 2: названы два категорийных из четырёх", "milk-oolong", "Цветочность и сладкое послевкусие есть у улунов вообще.", true],
    ["проба 3: пустой блок", "longjing", "Так описывают зелёные чаи вообще.", true],
    /* Предел, а не дыра к починке: распознавание «рамка называет дескриптор»
       отсекает окончания и на другом корне промахивается. Лежит пробой, а не
       комментарием, чтобы проверялся каждым прогоном. */
    ["предел: рамка называет дескриптор другим корнем", "menghai-shu", "Возврат сладости есть у шу-пуэров вообще.", "known"],
];

console.log("\nпробы:");
for (const [name, slug, scope, mustFail] of PROBES) {
    const tea = teas.find((t) => t.slug === slug);
    let block = blockOf(tea);
    if (name.startsWith("проба 3")) block = [];
    if (name.startsWith("проба 2")) {
        block = blockOf(tea).filter(([d, f]) => BY_TYPE_PROFILE.has(`${slug}|${low(d)}|${f}`) || OWN.has(`${slug}|${low(d)}`));
    }
    const bad = audit(slug, scope, block);

    if (mustFail === "known") {
        console.log(
            `  ${bad.length ? "✅ неожиданно ловится" : "⚠ известный предел, не ловится"}  ${name}`,
        );
        continue;
    }

    const ok = mustFail ? bad.length > 0 : bad.length === 0;
    if (!ok) process.exitCode = 1;
    console.log(`  ${ok ? "✅" : "⚠ НЕ ЛОВИТСЯ"}  ${name}`);
    for (const line of bad) console.log(`        ${line}`);
}

/*
 * Долг печатается, а не лежит в комментарии.
 *
 * Покрытие ниже перечислено руками, потому что происхождения у дескриптора
 * в данных нет. Предел в докблоке проверяется один раз, при чтении; строка
 * в выводе — при каждом прогоне. Список молча не устареет, он просто
 * разойдётся с фактурой, и заметить это должен тот, кто смотрит вывод.
 */
console.log(
    `\nДОЛГ: покрытие профилем перечислено в этом файле руками (20 строк), ` +
        "потому что у дескриптора в данных нет происхождения.\n" +
        "  Выбросить, когда characteristics получит sources и confidence — задача seo.",
);
